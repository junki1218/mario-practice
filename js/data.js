const COIN_ROUNDS_MIN = 3;
const COIN_ROUNDS_MAX = 8;

// コインフェーズが終わって最初の「スー」に戻るときの分岐（ダミーは少しトリッキーに）
const COIN_EXIT_DUMMIES = ["1UP", "マリオ"];

// ==================================================================
// エフェクト・演出まわりの時間調整（ミリ秒）
