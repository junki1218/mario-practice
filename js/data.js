// ==================================================================
// 「スーパーマリオ」フレーズの正しい進行ルール（ユーザー確定版）：
//
//   スー → パー → マリ → オ → スーパー → マリオ → スーパーマリオ → コイン
//
// 最初の4ラウンドで「スーパーマリオ」を2文字ずつの断片に分けて1つずつ発言し、
// 続く3ラウンドでその断片を組み合わせて言葉を組み立てていく。
// 最後に完成した「スーパーマリオ」の次からコインフェーズへ入る。
//
// 各要素: { prev: 前の人が言った単語, correct: 正解, dummies: [ダミー2つ] }
// ==================================================================
const BUILD_SEQUENCE = [
  { prev: "スー",           correct: "パー",           dummies: ["マリ", "オ"] },
  { prev: "パー",           correct: "マリ",           dummies: ["オ", "スーパー"] },
  { prev: "マリ",           correct: "オ",             dummies: ["スーパー", "マリオ"] },
  { prev: "オ",             correct: "スーパー",       dummies: ["マリオ", "スーパーマリオ"] },
  { prev: "スーパー",       correct: "マリオ",         dummies: ["スーパーマリオ", "コイン"] },
  { prev: "マリオ",         correct: "スーパーマリオ", dummies: ["コイン", "スー"] },
  { prev: "スーパーマリオ", correct: "コイン",         dummies: ["スー", "パー"] },
];

// ゲーム開始直後、最初に画面に出す「前の人」の言葉（＝一番最初のお題）
const GAME_START_WORD = "スー";

// ==================================================================
